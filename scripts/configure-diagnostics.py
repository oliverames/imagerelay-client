#!/usr/bin/env python3
"""Write the ignored Sentry build configuration from 1Password without displaying the DSN.

The Sentry DSN is Sentry's public ingestion key. It is kept out of Git anyway, so forks and CI
builds run with crash reporting off. The op:// reference is resolved, validated and written to
Config/Diagnostics.local.xcconfig with mode 600. --verify-app compares a built app's Info.plist,
and its extensions', with the same reference. --remove deletes the local file. No Sentry request is made here.
"""
import argparse
import os
from pathlib import Path
import plistlib
import re
import subprocess
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REFERENCE = "op://Development/Image Relay Sentry DSN/credential"
TARGET = ROOT / "Config/Diagnostics.local.xcconfig"
PLIST_KEY = "ImageRelaySentryDSN"


def validate_dsn(value):
    """Accept only a public HTTPS sentry.io ingestion DSN, without a secret key or query."""
    try:
        url = urlsplit(value)
        valid = (
            url.scheme == "https"
            and url.hostname is not None
            and url.hostname.endswith(".sentry.io")
            and re.fullmatch(r"[a-z0-9.-]+", url.hostname)
            and re.fullmatch(r"[A-Za-z0-9]{16,128}", url.username or "")
            and url.password is None
            and url.port is None
            and re.fullmatch(r"/[0-9]+", url.path)
            and not url.query and not url.fragment
            and not any(c.isspace() for c in value)
        )
    except ValueError:
        valid = False
    if not valid:
        raise ValueError("not a public HTTPS Sentry DSN")
    return value


def configuration(dsn):
    # xcconfig treats // as a comment even inside a value. The empty build setting reference
    # splits the slashes and expands to nothing in Info.plist.
    escaped = validate_dsn(dsn).replace("https://", "https:/$()/", 1)
    return (
        "// Generated by scripts/configure-diagnostics.py from 1Password. Do not commit or print.\n"
        f"IMAGERELAY_SENTRY_DSN = {escaped}\n"
    )


def resolve(reference):
    result = subprocess.run(["op", "read", reference], capture_output=True, text=True, check=False)
    if result.returncode:
        # 1Password output can echo values; never show it.
        raise ValueError("1Password could not resolve the reference")
    return validate_dsn(result.stdout.strip())


def verify_app(app, value):
    """Check the app and every extension inside it (the File Provider extension)."""
    bundles = [app] + sorted((app / "Contents/PlugIns").glob("*.appex"))
    for bundle in bundles:
        with (bundle / "Contents/Info.plist").open("rb") as stream:
            info = plistlib.load(stream)
        if info.get(PLIST_KEY, "") != value:
            raise ValueError(f"{bundle.name} value differs")


def write_local(target, text):
    target.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "w") as stream:
        os.fchmod(stream.fileno(), 0o600)
        stream.truncate(0)
        stream.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dsn-reference", default=DEFAULT_REFERENCE,
                        help="op:// reference to the Sentry DSN; never a literal value")
    parser.add_argument("--verify-app", type=Path, help="check a built .app instead of writing")
    parser.add_argument("--remove", action="store_true", help="delete the local configuration file")
    args = parser.parse_args()
    if args.remove:
        TARGET.unlink(missing_ok=True)
        print("PASS: local configuration removed. Builds now run with crash reporting off.")
        return 0
    if not args.dsn_reference.startswith("op://"):
        parser.error("the reference must be an op:// reference")
    try:
        value = resolve(args.dsn_reference)
        if args.verify_app:
            verify_app(args.verify_app, value)
            print("PASS: the built app's Sentry DSN matches 1Password. No values displayed.")
        else:
            write_local(TARGET, configuration(value))
            print(f"PASS: wrote {TARGET.relative_to(ROOT)}. No values displayed.")
    except (ValueError, OSError, plistlib.InvalidFileException) as error:
        print(f"FAIL: Sentry DSN: {error}. No values displayed.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
